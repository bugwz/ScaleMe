"""Generate offline WHO BMI LMS tables from the four official expanded XLSX files.

Usage: python3 Tools/HealthReference/GenerateWHOBodyMassReference.py DIRECTORY
DIRECTORY contains child-boys.xlsx, child-girls.xlsx, youth-boys.xlsx,
and youth-girls.xlsx. Output is Swift source on stdout; no network access.
Sources and file hashes are included in the generated source for reproducibility.
"""
import hashlib
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
import zipfile

BASE = "https://cdn.who.int/media/docs/default-source/child-growth/"
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
tables = []
for group, count, first in [("child", 1857, 0), ("youth", 168, 61)]:
    for sex in ["boys", "girls"]:
        path = Path(sys.argv[1]) / f"{group}-{sex}.xlsx"
        with zipfile.ZipFile(path) as archive:
            root = ET.fromstring(archive.read("xl/worksheets/sheet1.xml"))
            rows = []
            for row in root.findall(".//m:sheetData/m:row", NS)[1:]:
                cells = {cell.attrib["r"].rstrip("0123456789"): cell.find("m:v", NS).text
                         for cell in row.findall("m:c", NS) if cell.find("m:v", NS) is not None}
                rows.append([float(cells[k]) for k in ["A", "B", "C", "D"]])
        assert len(rows) == count
        assert all(row[0] == first + i and row[2] > 0 and row[3] > 0 for i, row in enumerate(rows))
        if group == "child":
            url = BASE + f"child-growth-standards/indicators/body-mass-index-for-age/expanded-tables/bfa-{sex}-zscore-expanded-tables.xlsx"
        else:
            url = BASE + f"growth-reference-5-19-years/bmi-for-age-(5-19-years)/bmi-{sex}-z-who-2007-exp.xlsx"
        tables.append((group + sex.title(), rows, url, hashlib.sha256(path.read_bytes()).hexdigest()))

print("// Generated by Tools/HealthReference/GenerateWHOBodyMassReference.py; do not edit tables manually.")
print("// WHO Child Growth Standards (2006) / Growth Reference (2007). No WHO endorsement implied.")
print("enum WHOBodyMassReferenceData {")
for name, rows, url, digest in tables:
    print(f"    // {url}\n    // SHA-256: {digest}")
    print(f'    static let {name} = """')
    for _, l, m, s in rows:
        print(f"    {l:.5f},{m:.5f},{s:.5f}")
    print('    """')
print("}")
